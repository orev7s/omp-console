#!/usr/bin/env bash
# Caddy installation and configuration.
#
# Caddy terminates TLS and reverse proxies to the control plane on loopback.
# The domain, IP, and private-network modes share the same site body; only the
# site address and certificate policy differ.

: "${OMP_CONSOLE_CADDY_VERSION:=2.11.9}"
: "${CADDY_CONF_DIR:=/etc/caddy/omp-console}"
: "${CADDY_DATA_DIR:=/var/lib/caddy}"
: "${CADDY_CONF_FILE:=${CADDY_CONF_DIR}/Caddyfile}"
: "${CADDY_ENV_FILE:=${CADDY_CONF_DIR}/caddy.env}"
: "${CADDY_MIN_VERSION:=2.10.1}"

caddy_installed_version() {
  if command -v caddy >/dev/null 2>&1; then
    caddy version 2>/dev/null | awk '{print $1}' | head -1
  fi
}

install_caddy() {
  local installed
  installed="$(caddy_installed_version || true)"
  if [ -n "$installed" ] && version_ge "$installed" "$CADDY_MIN_VERSION"; then
    CADDY_BIN="$(command -v caddy)"
    log_ok "Caddy ${installed} found at ${CADDY_BIN}."
    return
  fi

  if [ -n "$installed" ]; then
    log_warn "Caddy ${installed} is older than ${CADDY_MIN_VERSION}. Installing Caddy ${OMP_CONSOLE_CADDY_VERSION}."
  else
    log_info "Caddy is not installed. Installing Caddy ${OMP_CONSOLE_CADDY_VERSION}."
  fi

  case "$ARCH" in
    amd64) CADDY_ARCH="amd64" ;;
    arm64) CADDY_ARCH="arm64" ;;
    *) die "Unsupported architecture for Caddy: ${ARCH}." ;;
  esac

  local asset="caddy_${OMP_CONSOLE_CADDY_VERSION}_linux_${CADDY_ARCH}.tar.gz"
  local base="https://github.com/caddyserver/caddy/releases/download/v${OMP_CONSOLE_CADDY_VERSION}"

  if dry_run; then
    CADDY_BIN="${CADDY_BIN:-caddy}"
    log_info "Dry run: would install Caddy ${OMP_CONSOLE_CADDY_VERSION} (${CADDY_ARCH})."
    return
  fi

  local tmp
  tmp="$(make_temp_dir)"

  download "${base}/${asset}" "$tmp/${asset}"
  download "${base}/caddy_${OMP_CONSOLE_CADDY_VERSION}_checksums.txt" "$tmp/checksums.txt"

  local expected actual
  expected="$(grep "  ${asset}\$" "$tmp/checksums.txt" | awk '{print $1}' | head -1)"
  [ -n "$expected" ] || {
    rm -rf "$tmp"
    die "No checksum for ${asset}. Refusing to install Caddy."
  }
  actual="$(sha512_file "$tmp/${asset}")"
  if [ "$expected" != "$actual" ]; then
    rm -rf "$tmp"
    die "Caddy checksum verification failed. Refusing to install."
  fi

  run tar -xzf "$tmp/${asset}" -C "$tmp"
  [ -x "$tmp/caddy" ] || {
    rm -rf "$tmp"
    die "The Caddy archive did not contain a caddy binary."
  }
  run install -m 0755 "$tmp/caddy" /usr/local/bin/caddy
  rm -rf "$tmp"
  hash -r

  CADDY_BIN="/usr/local/bin/caddy"
  local now
  now="$("$CADDY_BIN" version 2>/dev/null | awk '{print $1}')"
  if ! dry_run && ! version_ge "$now" "$CADDY_MIN_VERSION"; then
    die "Installed Caddy ${now} is older than ${CADDY_MIN_VERSION}."
  fi
  log_ok "Caddy ${now:-$OMP_CONSOLE_CADDY_VERSION} installed at ${CADDY_BIN}."
}

ensure_caddy_user() {
  if id -u caddy >/dev/null 2>&1; then
    return
  fi
  if command -v useradd >/dev/null 2>&1; then
    run useradd --system --home "$CADDY_DATA_DIR" --shell /usr/sbin/nologin --user-group caddy
  elif command -v adduser >/dev/null 2>&1; then
    run adduser -S -H -h "$CADDY_DATA_DIR" -s /sbin/nologin caddy
  else
    die "Could not create the caddy user. Create it manually and rerun."
  fi
}

write_caddy_env() {
  local domain="$1"
  local web_root="$2"
  local upstream="$3"
  local email="$4"
  local mode="$5"

  {
    printf '# Generated by installer/install.sh. Do not edit by hand.\n'
    printf 'OMP_CONSOLE_WEB_ROOT=%s\n' "$web_root"
    printf 'OMP_CONSOLE_UPSTREAM=%s\n' "$upstream"
    if [ "$mode" = "ip" ]; then
      printf 'OMP_CONSOLE_PUBLIC_IP=%s\n' "$domain"
      printf 'OMP_CONSOLE_DEMO_HOST=%s\n' "$domain"
    else
      printf 'OMP_CONSOLE_DOMAIN=%s\n' "$domain"
      printf 'OMP_CONSOLE_DEMO_HOST=%s\n' "$domain"
      if [ -n "$email" ]; then
        printf 'OMP_CONSOLE_ACME_EMAIL=%s\n' "$email"
      fi
    fi
  } | atomic_write "$CADDY_ENV_FILE" 640
  if ! dry_run; then
    chown "root:caddy" "$CADDY_ENV_FILE"
  fi
}

configure_caddy() {
  local mode="$1"
  local domain="$2"
  local web_root="$3"
  local upstream="$4"
  local email="$5"

  ensure_caddy_user
  ensure_dir "$CADDY_CONF_DIR" 0750 "root:caddy"
  ensure_dir "$CADDY_DATA_DIR" 0700 "caddy:caddy"

  local template
  if [ "$mode" = "ip" ]; then
    template="${INSTALLER_DIR}/caddy/Caddyfile.ip"
  else
    template="${INSTALLER_DIR}/caddy/Caddyfile"
  fi
  [ -r "$template" ] || die "Caddy template not found: ${template}."
  if ! dry_run; then
    install -m 0644 "$template" "$CADDY_CONF_FILE"
  fi

  write_caddy_env "$domain" "$web_root" "$upstream" "$email" "$mode"

  log_info "Validating the Caddy configuration."
  if dry_run; then
    log_info "Dry run: would validate the Caddy configuration."
  else
    (
      set -a
      # shellcheck disable=SC1090
      . "$CADDY_ENV_FILE"
      set +a
      "$CADDY_BIN" validate --config "$CADDY_CONF_FILE" --adapter caddyfile
    ) || die "Caddy rejected the configuration. Check ${CADDY_CONF_FILE} and ${CADDY_ENV_FILE}."
    log_ok "Caddy configuration is valid."
  fi
}

install_caddy_unit() {
  local template="${INSTALLER_DIR}/systemd/omp-console-caddy.service.in"
  [ -r "$template" ] || die "Caddy unit template not found: ${template}."
  local rendered_dir rendered
  rendered_dir="$(make_temp_dir)"
  rendered="${rendered_dir}/omp-console-caddy.service"
  sed \
    -e "s|@CADDY_BIN@|${CADDY_BIN}|g" \
    -e "s|@CADDY_CONF_FILE@|${CADDY_CONF_FILE}|g" \
    -e "s|@CADDY_ENV_FILE@|${CADDY_ENV_FILE}|g" \
    -e "s|@CADDY_DATA_DIR@|${CADDY_DATA_DIR}|g" \
    "$template" >"$rendered"
  run install -m 0644 "$rendered" /etc/systemd/system/omp-console-caddy.service
  rm -f "$rendered"
  run systemctl daemon-reload
}

start_caddy() {
  if service_active omp-console-caddy; then
    run systemctl restart omp-console-caddy
  else
    run systemctl enable --now omp-console-caddy
  fi
}

stop_caddy() {
  if service_active omp-console-caddy; then
    run systemctl stop omp-console-caddy
  fi
  if service_enabled omp-console-caddy; then
    run systemctl disable omp-console-caddy
  fi
}